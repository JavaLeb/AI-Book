from pymilvus import MilvusClient, DataType, Function, FunctionType, AnnSearchRequest, RRFRanker

client = MilvusClient()

# 创建schema.
schema = MilvusClient.create_schema(auto_id=False)
# 创建主键字段.
schema.add_field(field_name="id", datatype=DataType.INT64,
                 is_primary=True, description="product id")
# 创建文本字段，并启动分析器.
schema.add_field(field_name="text", datatype=DataType.VARCHAR,
                 max_length=1000, enable_analyzer=True,
                 description="raw text of product description")
# 创建文本稀疏向量.
schema.add_field(field_name="text_sparse", datatype=DataType.SPARSE_FLOAT_VECTOR,
                 description="text sparse embedding auto-generated by the built-in BM25 function")
# 创建文本稠密向量.
schema.add_field(field_name="text_dense", datatype=DataType.FLOAT_VECTOR,
                 dim=3, description="text dense embedding")
# 创建图像稠密向量.
schema.add_field(field_name="image_dense", datatype=DataType.FLOAT_VECTOR,
                 dim=2, description="image dense embedding")

# 创建BM25函数: 将文本字段值自动转换为稀疏向量.
bm25_function = Function(
    name="text_bm25_emb",
    input_field_names=["text"],
    output_field_names=["text_sparse"],
    function_type=FunctionType.BM25,
)
schema.add_function(bm25_function)

# 创建索引.
index_params = client.prepare_index_params()
# 文本稠密向量, 使用自动索引，度量类型：内积.
index_params.add_index(
    field_name="text_dense", index_name="text_dense_index",
    index_type="AUTOINDEX", metric_type="IP")
# 文本稀疏向量，使用稀疏逆索引，度量类型：BM25.
index_params.add_index(
    field_name="text_sparse", index_name="text_sparse_index",
    index_type="SPARSE_INVERTED_INDEX", metric_type="BM25",
    params={"inverted_index_algo": "DAAT_MAXSCORE"})
# 图像稠密向量，使用自动索引，度量类型：内积.
index_params.add_index(
    field_name="image_dense", index_name="image_dense_index",
    index_type="AUTOINDEX", metric_type="IP")

# 创建集合.
collection_name = 'my_collection'
client.create_collection(
    collection_name=collection_name, schema=schema,
    index_params=index_params)

# 数据模拟, 假设已经通过嵌入模型得到文本和图像稠密向量.
data = [
    {"id": 0, "text": "Red cotton t-shirt with round neck",
     "text_dense": [0.3580376395471989, -0.6023495712049978, 0.18414012509913835],
     "image_dense": [0.6366019600530924, -0.09323198122475052]},
    {"id": 1, "text": "Wireless noise-cancelling over-ear headphones",
     "text_dense": [0.19886812562848388, 0.06023560599112088, 0.6976963061752597],
     "image_dense": [0.6414180010301553, 0.8976979978567611]},
    {"id": 2, "text": "Stainless steel water bottle, 500ml",
     "text_dense": [0.43742130801983836, -0.5597502546264526, 0.6457887650909682],
     "image_dense": [-0.6901259768402174, 0.6100500332193755]}]
# 插入数据.
res = client.insert(collection_name=collection_name, data=data)

# 混合搜索.
query_text = "white headphones, quiet and comfortable"  # 查询文本.
query_dense_vector = [0.3580376395471989, -0.6023495712049978, 0.5142999509918703]
query_multimodal_vector = [0.015829865178701663, 0.5264158340734488]
# 文本稠密向量搜索.
search_param_1 = {
    "data": [query_dense_vector], "anns_field": "text_dense",
    "param": {"nprobe": 10}, "limit": 2
}
request_1 = AnnSearchRequest(**search_param_1)  # 初始化ANN搜索请求.
# 文本稀疏向量搜索.
search_param_2 = {
    "data": [query_text], "anns_field": "text_sparse",
    "param": {"drop_ratio_search": 0.2}, "limit": 2
}
request_2 = AnnSearchRequest(**search_param_2)
# 图像稠密向量搜索.
search_param_3 = {
    "data": [query_multimodal_vector], "anns_field": "image_dense",
    "param": {"nprobe": 10}, "limit": 2
}
request_3 = AnnSearchRequest(**search_param_3)

reqs = [request_1, request_2, request_3]

ranker = RRFRanker(100)  # 重排.
# 混合搜索: 每个ANN搜索请求返回2个结果, 总计返回6个结果.
# 使用重排，最终返回2个实体.
res = client.hybrid_search(
    collection_name=collection_name,
    reqs=reqs, ranker=ranker, limit=2)
for hits in res:
    print("TopK results:")
    for hit in hits:
        print(hit)
